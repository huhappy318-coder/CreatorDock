test('keeps new content exportable when browser storage is full', async ({ page }) => {
  await page.addInitScript(() => {
    const original = Storage.prototype.setItem
    Storage.prototype.setItem = function(key, value) {
      if (key === 'creatordock.distributions.v1') throw new DOMException('Quota exceeded', 'QuotaExceededError')
      return original.call(this, key, value)
    }
  })
  await page.goto('')
  await create(page, '存储失败也不丢失')
  await expect(page.getByRole('alert')).toContainText('保存失败')
  await expect(page.getByRole('button', { name:'查看分发：存储失败也不丢失' })).toBeVisible()
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name:'导出当前备份' }).click()])
  const backup = JSON.parse(await readFile((await download.path())!, 'utf8'))
  expect(backup.records[0].title).toBe('存储失败也不丢失')
  expect(backup.records[0].targets).toHaveLength(2)
})

test('carries selected content into AI without overwriting its draft and imports completed package variants', async ({ page }) => {
  await page.addInitScript(() => {
    localStorage.setItem('creatordock.writing.draft.v1', '已有写作草稿')
  })
  await page.goto('')
  await create(page, 'AI 适配来源')
  await page.getByRole('button', { name: 'AI 辅助适配 ↗', exact:true }).click()
  await expect(page.getByLabel('待适配内容')).toContainText('AI 适配来源')
  await expect(page.getByLabel('写作任务', { exact:true })).toHaveValue('已有写作草稿')
  await page.getByRole('button', { name:'带入写作任务',exact:true }).click()
  await expect(page.getByLabel('写作任务', { exact:true })).toHaveValue(/已有写作草稿[\s\S]*AI 适配来源/)
  const entries = await page.evaluate(() => JSON.parse(localStorage.getItem('creatordock.config') ?? 'null'))
  // Default entries are not saved until changed; use a seeded configuration for package migration.
  expect(entries === null || Array.isArray(entries.entries)).toBe(true)
  await page.evaluate(() => {
    const distribution = JSON.parse(localStorage.getItem('creatordock.distributions.v1')!).records[0]
    const targets = distribution.targets.map((t: {entry:{id:string;displayName:string;platformPresetId?:string}}) => ({id:t.entry.id,label:t.entry.displayName,platformPresetId:t.entry.platformPresetId}))
    const config = { schemaVersion:2, language:'zh-CN', theme:'light', density:'comfortable', entries:distribution.targets.map((t:{entry:unknown})=>t.entry) }
    localStorage.setItem('creatordock.config', JSON.stringify(config))
    localStorage.setItem('creatordock.content-packages.v1', JSON.stringify([{schemaVersion:1,id:'import-package',brief:'历史 AI 内容包',targets,variants:targets.map((target:{id:string},i:number)=>({id:`variant-${i}`,target,output:`第 ${i+1} 份独立稿件`,status:'complete'})),createdAt:new Date().toISOString(),updatedAt:new Date().toISOString()}]))
  })
  await page.reload()
  await page.getByRole('button', { name:'加入分发队列',exact:true }).click()
  await expect(page.getByRole('heading', { name:'分发工作台',exact:true })).toBeVisible()
  const records = await page.evaluate(key=>JSON.parse(localStorage.getItem(key)!).records,key)
  expect(records).toHaveLength(2)
  expect(records[0].targets.map((t:{body:string})=>t.body)).toEqual(['第 1 份独立稿件','第 2 份独立稿件'])
  expect(await page.evaluate(()=>localStorage.getItem('creatordock.content-packages.v1'))).toContain('import-package')
})

