test('keeps both versions when two tabs edit the same content', async ({page, context}) => {
  await page.goto('')
  await create(page, '共同编辑的内容')
  const other = await context.newPage()
  await other.goto('')
  await page.getByRole('button',{name:'编辑内容',exact:true}).click()
  await other.getByRole('button',{name:'编辑内容',exact:true}).click()
  const otherEditor = other.getByRole('dialog',{name:'编辑分发内容'})
  await otherEditor.getByLabel('正文',{exact:true}).fill('另一标签页独有的修改')
  await otherEditor.getByRole('button',{name:'保存修改'}).click()
  const editor = page.getByRole('dialog',{name:'编辑分发内容'})
  await editor.getByLabel('正文',{exact:true}).fill('当前标签页独有的修改')
  await editor.getByRole('button',{name:'保存修改'}).click()
  await expect(page.getByText(/检测到其他标签页修改了相同内容/)).toBeVisible()
  await page.reload()
  const records = await page.evaluate(key=>JSON.parse(localStorage.getItem(key)!).records,key)
  expect(records).toHaveLength(2)
  expect(records.map((r:{body:string})=>r.body)).toEqual(expect.arrayContaining(['另一标签页独有的修改','当前标签页独有的修改']))
})

