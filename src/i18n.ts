export function platformLabel(platformId: string | undefined, language: LanguageSetting | undefined, fallback?: string): string {
  if (!platformId) return fallback ?? translate(language, 'customDestination')
  const names = platformNames[platformId]
  return names?.[language === 'en' ? 'en' : 'zh-CN'] ?? fallback ?? platformId
}

export function platformSearchLabels(platformId: string | undefined): string[] {
  const names = platformId ? platformNames[platformId] : undefined
  return names ? [...new Set(Object.values(names))] : []
}

