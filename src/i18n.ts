export function translate(language: LanguageSetting | undefined, key: TranslationKey, values: Record<string, string | number> = {}): string {
  const template = translations[language === 'en' ? 'en' : DEFAULT_LANGUAGE][key]
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`))
}

